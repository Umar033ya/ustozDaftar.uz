/** Pure lookup with a safe fallback chain: lang -> default lang -> key. */
export function translate(lang, key) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  const value = dict[key];
  if (value !== undefined) return value;
  const fallback = translations[DEFAULT_LANG][key];
  return fallback !== undefined ? fallback : key;
}

/** Replace {name} placeholders in a translated string. */
export function interpolate(template, vars) {
  if (typeof template !== "string" || !vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

/** Read the persisted language from localStorage (browser only, SSR-safe). */
export function readStoredLang() {
  if (typeof window === "undefined") return null;
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return SUPPORTED_LANGS.includes(stored) ? stored : null;
  } catch {
    return null;
  }
}

/** Persist the language to localStorage (browser only). */
export function persistLang(lang) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // storage may be unavailable (private mode); language still works for the session
  }
}
